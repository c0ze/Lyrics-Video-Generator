/* Build src/Arda/lyrics.data.ts from the Arda site (single source of truth).
 *
 * Reads the site's data/songs.js (sin/en + section kind), data/tengwar.js
 * (sin -> Tengwar), and lyrics/<id>.lrc (timestamps), zips them by index, and
 * emits timed lines { timeSec, teng, en, kind } per song for the video.
 *
 *   node scripts/build-arda-data.mjs
 *   ARDA_SITE_DIR=/path/to/arda node scripts/build-arda-data.mjs
 */
import fs from "fs";
import vm from "vm";
import path from "path";
import { fileURLToPath } from "url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SITE = process.env.ARDA_SITE_DIR || "/Users/arda/projects/arda/arda";

function loadGlobals(file) {
  const sandbox = { window: {} };
  vm.runInNewContext(fs.readFileSync(file, "utf8"), sandbox);
  return sandbox.window;
}

const songs = loadGlobals(path.join(SITE, "data/songs.js")).ARDA_SONGS;
const teng = loadGlobals(path.join(SITE, "data/tengwar.js")).ARDA_TENGWAR;

function lrcTimes(id) {
  const file = path.join(SITE, "lyrics", `${id}.lrc`);
  const out = [];
  for (const line of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\[(\d+):(\d+(?:\.\d+)?)\]/);
    if (m) out.push(parseInt(m[1], 10) * 60 + parseFloat(m[2]));
  }
  return out.sort((a, b) => a - b);
}

const data = {};
for (const song of songs) {
  const flat = [];
  for (const sec of song.sections) for (const l of sec.lines) flat.push({ ...l, kind: sec.kind });
  const times = lrcTimes(song.id);
  if (times.length !== flat.length) {
    throw new Error(`${song.id}: ${flat.length} lyric lines vs ${times.length} lrc timestamps — re-sync.`);
  }
  data[song.id] = {
    title: song.title,
    titleEn: song.titleEn,
    titleTeng: teng[song.title] || song.title,
    lines: flat.map((l, i) => ({ timeSec: times[i], teng: teng[l.sin] || l.sin, en: l.en, kind: l.kind })),
  };
  console.log(`  ${song.id}: ${flat.length} lines`);
}

const header = "/* Generated by scripts/build-arda-data.mjs — do not edit by hand. */\n";
const body =
  "export interface ArdaLyricLine { timeSec: number; teng: string; en: string; kind: string; }\n" +
  "export interface ArdaSongData { title: string; titleEn: string; titleTeng: string; lines: ArdaLyricLine[]; }\n" +
  "export const ARDA_LYRICS: Record<string, ArdaSongData> = " +
  JSON.stringify(data, null, 2) +
  ";\n";
fs.writeFileSync(path.join(ROOT, "src/Arda/lyrics.data.ts"), header + body);
console.log(`Wrote src/Arda/lyrics.data.ts (${Object.keys(data).length} songs).`);
